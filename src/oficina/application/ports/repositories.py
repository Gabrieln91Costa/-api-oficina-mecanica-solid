from typing import Protocol, Any
from uuid import UUID

class OficinaRepository(Protocol):
    def criar_cliente(self, dados: dict[str, Any]) -> Any: ...
    def criar_veiculo(self, dados: dict[str, Any]) -> Any: ...
    def criar_servico(self, dados: dict[str, Any]) -> Any: ...
    def criar_peca(self, dados: dict[str, Any]) -> Any: ...
    def abrir_os(self, dados: dict[str, Any]) -> Any: ...
    def buscar_os(self, ordem_id: UUID) -> Any | None: ...
    def listar_os_operacionais(self) -> list[Any]: ...
    def atualizar_status(self, ordem_id: UUID, status: str, origem: str) -> Any: ...
    def criar_orcamento(self, ordem_id: UUID, dados: dict[str, Any]) -> Any: ...
    def decidir_orcamento(self, orcamento_id: int, aprovado: bool, ator: str) -> Any: ...
    def registrar_evento(self, event_id: str, payload: dict[str, Any]) -> bool: ...
